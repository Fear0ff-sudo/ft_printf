#include "ft_printf.h"

void	ft_bin_reverse(char *s)
{
	int	i;

	i = 0;
	while (s[i])
	{
		if (s[i] == '0')
			s[i] = '1';
		else
			s[i] = '0';
		i++;
	}
}
